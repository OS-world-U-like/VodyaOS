#!/usr/bin/env python3
"""Generate port/<arch>/kernel/cjkfont.h from GNU Unifont .hex data.

One-shot generator: the output is committed to the repo so the kernel
build never depends on the download.  To regenerate (e.g. newer Unifont):

    curl -sL -o /tmp/unifont_all.hex.gz \
        https://ftp.gnu.org/gnu/unifont/unifont-15.1.05/unifont_all-15.1.05.hex.gz
    python3 tools/gencjkfont.py /tmp/unifont_all.hex.gz \
        port/x86_64/kernel/cjkfont.h

Coverage: the GB2312 charset (full-width punctuation/symbols in rows
0xA1-0xA9 plus all level-1/level-2 hanzi, rows 0xB0-0xF7) -- 6891 glyphs
at 16x16, looked up by Unicode codepoint via binary search.
"""

import gzip
import sys


def gb2312_codepoints():
    """Unicode codepoints of the whole GB2312 double-byte charset."""
    cps = set()
    for hi in range(0xA1, 0xF8):
        if hi > 0xA9 and hi < 0xB0:
            continue			# empty rows between symbols and hanzi
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes([hi, lo]).decode("gb2312")
            except UnicodeDecodeError:
                continue
            cps.add(ord(ch))
    # extras: common in Chinese text but outside (or absent from) GB2312
    cps.add(0x2014)			# — em dash (GB2312 uses U+2015)
    return sorted(cps)


def main():
    src, dst = sys.argv[1], sys.argv[2]
    opener = gzip.open if src.endswith(".gz") else open
    with opener(src, "rt") as f:
        glyphs = {}
        for line in f:
            cp, _, bits = line.strip().partition(":")
            glyphs[int(cp, 16)] = bytes.fromhex(bits)

    cps, missing, fixed = [], [], {}
    for cp in gb2312_codepoints():
        g = glyphs.get(cp)
        if g is None:
            missing.append(cp)
            continue
        if len(g) == 16:
            # unifont draws this codepoint halfwidth: pad each row to the
            # 16px cell (glyph in the left 8 columns)
            g = bytes(b for r in g for b in (r, 0))
        if len(g) == 32:
            cps.append(cp)
            fixed[cp] = g
    if missing:
        print("gencjkfont: WARNING %d GB2312 codepoints missing from unifont"
              % len(missing), file=sys.stderr)

    rows = []
    for cp in cps:
        g = fixed[cp]
        hexs = ",".join("0x%02x" % b for b in g)
        try:
            label = chr(cp)
        except ValueError:
            label = "?"
        rows.append("\t%s,\t/* U+%04X %s */" % (hexs, cp, label))

    with open(dst, "w") as out:
        out.write("""\
/*
 * 16x16 CJK bitmap font covering GB2312 (symbols 0xA1-0xA9 rows and
 * level-1/2 hanzi), %d glyphs, indexed by Unicode codepoint and sorted
 * for binary search.  GENERATED by tools/gencjkfont.py from %s
 * (GNU Unifont, GNU GPL 2+) -- do not edit by hand.
 * Each glyph is 32 bytes: 16 rows x 2 bytes, bit 7 of the first byte is
 * the leftmost pixel of the left half.
 */
#define CJK_GLYPH_BYTES	32

const unsigned short cjk_cp[] = {
%s
};

const unsigned char cjk_bits[][CJK_GLYPH_BYTES] = {
%s
};
""" % (len(cps), src,
       "".join("\t0x%04x,\t/* %s */\n" % (cp, _label(cp))
               for cp in cps),
       "\n".join(rows)))
    print("gencjkfont: %s (%d glyphs)" % (dst, len(cps)))


def _label(cp):
    try:
        return chr(cp)
    except ValueError:
        return "?"


if __name__ == "__main__":
    main()
