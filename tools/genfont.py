#!/usr/bin/env python3
"""Generate port/<arch>/kernel/font.h from a PSF console font.

One-shot generator: the output is committed to the repo so the kernel
build never depends on host fonts.  Run again only to change the font:

    python3 tools/genfont.py \
        /usr/share/consolefonts/Lat2-VGA16.psf.gz \
        port/x86_64/kernel/font.h

Parses PSF1 and PSF2 headers (with or without a unicode table; ASCII
32..126 maps 1:1 onto glyph indices for the fonts we use) and emits the
printable-ASCII glyphs as a C array.
"""

import gzip
import sys

FIRST, LAST = 0x20, 0x7e		# printable ASCII
NAME = "font8x16"


def psf1_glyphs(data):
    # PSF1: magic 0x36 0x04, mode byte, charsize byte; glyph i at 4+i*charsize
    if data[0] != 0x36 or data[1] != 0x04:
        return None
    mode, charsize = data[2], data[3]
    n = 512 if (mode & 0x02) else 256
    height = charsize			# PSF1 glyphs are always 8 wide
    return [data[4 + i * charsize: 4 + (i + 1) * charsize] for i in range(n)], height


def psf2_glyphs(data):
    # PSF2: magic 72 b5 4a 86, then little-endian u32 header fields
    if bytes(data[:4]) != bytes([0x72, 0xB5, 0x4A, 0x86]):
        return None
    f = lambda o: int.from_bytes(data[o:o + 4], "little")
    headersize, length, charsize, height, width = f(8), f(16), f(20), f(24), f(28)
    assert width == 8, "only 8px-wide fonts supported (got %d)" % width
    gsize = charsize
    return [data[headersize + i * gsize: headersize + (i + 1) * gsize]
            for i in range(length)], height


def main():
    src, dst = sys.argv[1], sys.argv[2]
    opener = gzip.open if src.endswith(".gz") else open
    with opener(src, "rb") as f:
        data = f.read()
    glyphs, height = psf1_glyphs(data) or psf2_glyphs(data)
    if glyphs is None:
        sys.exit("not a PSF font: %s" % src)

    rows = []
    for cp in range(FIRST, LAST + 1):
        g = glyphs[cp]
        rows.append("\t" + " ".join("0x%02x," % b for b in g) + "\t/* %s */\n"
                    % chr(cp).replace("\\", "\\\\").replace("*/", "*\\/"))
    body = "".join(rows)

    with open(dst, "w") as out:
        out.write("""\
/*
 * 8x%02d bitmap font, printable ASCII 0x20..0x7e, one row per byte.
 * GENERATED by tools/genfont.py from %s -- do not edit by hand.
 * Bit 7 of each byte is the leftmost pixel.
 */
#define FONT_WIDTH	8
#define FONT_HEIGHT	%d
#define FONT_FIRST	0x%02x
#define FONT_LAST	0x%02x

const unsigned char %s[][FONT_HEIGHT] = {
%s
};
""" % (height, src, height, FIRST, LAST, NAME, body))
    print("genfont: %s (%d glyphs, %dx%d)" % (dst, len(glyphs), 8, height))


if __name__ == "__main__":
    main()
